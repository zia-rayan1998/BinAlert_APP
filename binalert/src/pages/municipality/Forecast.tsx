import { useEffect, useState } from 'react';
import { CalendarRange, Info, Sparkles, TrendingUp } from 'lucide-react';
import { Card, CardHeader, PageHeader, StatCard } from '../../components/ui/Card';
import { Button } from '../../components/ui/Button';
import { Badge } from '../../components/ui/Badge';
import { ErrorState, ProgressBar, Skeleton } from '../../components/ui/Feedback';
import { Tabs } from '../../components/ui/Misc';
import { ForecastChart } from '../../components/charts/Charts';
import { forecastService } from '../../services/forecastService';
import { formatNumber } from '../../utils/format';
import type { ForecastPoint } from '../../types';

type Summary = Awaited<ReturnType<typeof forecastService.summary>>;

export function MunicipalityForecast() {
  const [horizon, setHorizon] = useState<'7' | '30'>('7');
  const [series, setSeries] = useState<ForecastPoint[] | null>(null);
  const [summary, setSummary] = useState<Summary | null>(null);
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(false);

  useEffect(() => {
    let alive = true;
    setLoading(true);
    setError('');
    Promise.all([forecastService.series(horizon === '7' ? 7 : 30), forecastService.summary()])
      .then(([s, sum]) => {
        if (!alive) return;
        setSeries(s);
        setSummary(sum);
      })
      .catch(() => alive && setError('The forecasting service did not respond.'))
      .finally(() => alive && setLoading(false));
    return () => {
      alive = false;
    };
  }, [horizon]);

  const capacityPlan = summary
    ? [
        { label: 'Daily collection capacity', value: '1,400 kg', note: 'current fleet' },
        { label: 'Predicted daily load', value: `${formatNumber(summary.predictedNextWeekKgDay)} kg`, note: 'next 7 days' },
        { label: 'Headroom', value: `${formatNumber(1400 - summary.predictedNextWeekKgDay)} kg`, note: summary.predictedNextWeekKgDay > 1400 ? 'capacity exceeded' : 'within capacity' },
        { label: 'Extra runs suggested', value: summary.predictedNextWeekKgDay > 1350 ? '2 per week' : '0', note: 'Zone B surge' },
      ]
    : [];

  return (
    <>
      <PageHeader
        breadcrumb="Municipal intelligence"
        title="Waste Forecasting"
        subtitle="Historical generation versus modelled demand, with confidence bands and zone breakdown."
        actions={
          <Tabs
            tabs={[
              { id: '7', label: '7-day' },
              { id: '30', label: '30-day' },
            ]}
            active={horizon}
            onChange={(id) => setHorizon(id as '7' | '30')}
          />
        }
      />

      <div className="mb-5 flex flex-wrap items-center gap-2 rounded-xl border border-amber-200 bg-amber-50 px-4 py-3">
        <Info className="h-4 w-4 shrink-0 text-amber-600" aria-hidden />
        <p className="text-xs font-medium leading-relaxed text-amber-900">
          <strong>Demo mode.</strong> Forecasts are generated by the in-browser ForecastingService with simulated Prophet-style seasonality.
          Connect the Python AI service (<code className="ba-num">VITE_AI_API_URL</code>) to serve live model predictions from{' '}
          <code className="ba-num">POST /api/ai/forecast</code>.
        </p>
      </div>

      {error ? (
        <ErrorState body={error} onRetry={() => setHorizon(horizon)} />
      ) : (
        <>
          <div className="grid gap-5 sm:grid-cols-2 xl:grid-cols-4">
            <StatCard loading={!summary} label="Current average" value={summary ? formatNumber(summary.currentAverageKgDay) : ''} unit="kg/day" icon={<TrendingUp className="h-5 w-5" />} hint="trailing 30 days" />
            <StatCard loading={!summary} label="Predicted next week" value={summary ? formatNumber(summary.predictedNextWeekKgDay) : ''} unit="kg/day" icon={<Sparkles className="h-5 w-5" />} delta={`+${summary?.expectedIncreasePct ?? 0}%`} deltaTone="down" />
            <StatCard loading={!summary} label="Expected increase" value={summary?.expectedIncreasePct ?? ''} unit="%" icon={<CalendarRange className="h-5 w-5" />} hint="versus current average" deltaTone="flat" />
            <StatCard loading={!summary} label="Model confidence" value={summary?.confidence ?? ''} unit="%" icon={<TrendingUp className="h-5 w-5" />} delta="band coverage" />
          </div>

          <Card className="mt-6">
            <CardHeader
              title={`Historical vs predicted — ${horizon}-day horizon`}
              subtitle="Solid line is measured generation; dashed line is the model forecast with its confidence band."
              action={<Badge className="bg-ink-100 text-ink-600 border-ink-200">{summary?.model ?? 'loading…'}</Badge>}
            />
            {loading && !series ? (
              <Skeleton className="h-[21rem] w-full" />
            ) : series ? (
              <ForecastChart data={series} />
            ) : null}
          </Card>

          <div className="mt-6 grid gap-6 xl:grid-cols-3">
            <Card className="xl:col-span-2">
              <CardHeader title="Zone-based prediction" subtitle="Where the next surge is expected" />
              {!summary ? (
                <Skeleton className="h-48 w-full" />
              ) : (
                <ul className="space-y-4">
                  {summary.zonePredictions.map((z) => (
                    <li key={z.zone}>
                      <div className="mb-1.5 flex flex-wrap items-center justify-between gap-2">
                        <span className="text-sm font-bold text-ink-900">{z.zone}</span>
                        <span className="ba-num text-sm font-bold text-ink-700">
                          {formatNumber(z.kgDay)} kg/day
                          <span className={`ml-2 text-xs ${z.deltaPct > 6 ? 'text-red-600' : 'text-emerald2-600'}`}>
                            {z.deltaPct > 0 ? '+' : ''}{z.deltaPct}%
                          </span>
                        </span>
                      </div>
                      <ProgressBar value={Math.min(100, (z.kgDay / 600) * 100)} tone={z.deltaPct > 6 ? 'red' : 'emerald'} label={`${z.zone} predicted load`} />
                    </li>
                  ))}
                </ul>
              )}
            </Card>

            <Card>
              <CardHeader title="Seasonal outlook" subtitle="Operational guidance from the model" />
              {!summary ? (
                <Skeleton className="h-48 w-full" />
              ) : (
                <div className="space-y-4">
                  <p className="text-sm leading-relaxed text-ink-600">{summary.seasonalNote}</p>
                  <div className="rounded-xl border border-forest-200 bg-forest-50 p-4">
                    <p className="ba-label text-forest-800">Model confidence</p>
                    <p className="ba-num mt-1 text-3xl font-extrabold text-forest-900">{summary.confidence}%</p>
                    <ProgressBar value={summary.confidence} tone="forest" className="mt-3" label="Model confidence" />
                  </div>
                  <Button variant="outline" className="w-full" onClick={() => setHorizon(horizon === '7' ? '30' : '7')}>
                    Switch to {horizon === '7' ? '30' : '7'}-day horizon
                  </Button>
                </div>
              )}
            </Card>
          </div>

          <Card className="mt-6">
            <CardHeader title="Capacity planning" subtitle="Predicted load against current collection capacity" />
            {!summary ? (
              <Skeleton className="h-32 w-full" />
            ) : (
              <ul className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
                {capacityPlan.map((c) => (
                  <li key={c.label} className="rounded-xl bg-ink-50 p-4 ring-1 ring-ink-100">
                    <p className="ba-label">{c.label}</p>
                    <p className="ba-num mt-1.5 text-xl font-extrabold text-ink-950">{c.value}</p>
                    <p className="mt-1 text-xs text-ink-400">{c.note}</p>
                  </li>
                ))}
              </ul>
            )}
          </Card>
        </>
      )}
    </>
  );
}
